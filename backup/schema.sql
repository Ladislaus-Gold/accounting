-- ---------- таблицы ----------

create table public.accounts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  currency text not null default 'UAH',
  is_monobank boolean not null default false,
  mono_account_id text unique,
  is_budget_source boolean not null default false
);
create unique index accounts_one_budget_source on public.accounts ((true)) where is_budget_source;

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null check (type = any (array['EXPENSE','INCOME'])),
  sort_order integer not null default 0,
  is_mandatory boolean not null default false,
  spend_mode text not null default 'spread' check (spend_mode = any (array['spread','chunks','lump'])),
  spend_parts integer not null default 4 check (spend_parts >= 2 and spend_parts <= 31),
  is_saving boolean not null default false,
  min_amount numeric not null default 0 check (min_amount >= 0),
  target_account_id bigint references public.accounts(id) on delete set null,
  constraint categories_name_type_key unique (name, type),
  constraint categories_mandatory_saving_check check (not (is_mandatory and is_saving))
);

create table public.transactions (
  id uuid primary key default gen_random_uuid(),
  date timestamptz not null,
  action text not null check (action = any (array['EXPENSE','INCOME','RETURN','TRANSFER'])),
  amount numeric not null check (amount > 0),
  category_id bigint references public.categories(id),
  account_id bigint references public.accounts(id),
  from_account_id bigint references public.accounts(id),
  to_account_id bigint references public.accounts(id),
  currency text not null default 'UAH',
  note text,
  mono_op_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index transactions_date_idx on public.transactions using btree (date desc);
create index transactions_category_id_idx on public.transactions using btree (category_id);

create table public.transaction_splits (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null references public.transactions(id) on delete cascade,
  category_id bigint not null references public.categories(id),
  amount numeric not null check (amount > 0),
  sort_order integer not null default 0
);
create index transaction_splits_tx_idx on public.transaction_splits using btree (transaction_id);

create table public.budgets (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  month date not null check (extract(day from month) = 1),
  amount numeric not null default 0,
  constraint budgets_category_id_month_key unique (category_id, month)
);

create table public.budget_distribution (
  category_id bigint not null references public.categories(id) on delete cascade,
  month date not null check (extract(day from month) = 1),
  advance numeric not null default 0 check (advance >= 0),
  salary numeric not null default 0 check (salary >= 0),
  other numeric not null default 0,
  primary key (category_id, month)
);

create table public.budget_distribution_month (
  month date primary key check (extract(day from month) = 1),
  advance_total numeric not null default 0 check (advance_total >= 0),
  salary_total numeric not null default 0 check (salary_total >= 0),
  formed_at timestamptz,
  transfer_ids uuid[] not null default '{}'::uuid[],
  batches jsonb not null default '[]'::jsonb
);

create table public.rules (
  id bigint generated by default as identity primary key,
  action text not null check (action = any (array['EXPENSE','INCOME','RETURN','TRANSFER'])),
  category_id bigint references public.categories(id) on delete cascade,
  note text not null,
  from_account_id bigint references public.accounts(id) on delete cascade,
  to_account_id bigint references public.accounts(id) on delete cascade,
  constraint rules_action_note_key unique (action, note),
  constraint rules_shape_check check (
    (action = 'TRANSFER' and from_account_id is not null and to_account_id is not null
       and category_id is null and from_account_id <> to_account_id)
    or
    (action <> 'TRANSFER' and category_id is not null
       and from_account_id is null and to_account_id is null)
  )
);

create table public.rules_import (
  action text,
  value text,
  note text
);

create table public.mono_state (
  id integer primary key default 1 check (id = 1),
  balance_kop bigint,
  credit_limit_kop bigint not null default 0,
  updated_at timestamptz not null default now(),
  source text
