create or replace view public.account_balances as
 with calc as (
   select a_1.id,
     (coalesce(sum(
        case
          when t.action = any (array['INCOME','RETURN']) and t.account_id = a_1.id then t.amount
          when t.action = 'EXPENSE' and t.account_id = a_1.id then -t.amount
          when t.action = 'TRANSFER' and t.to_account_id = a_1.id then t.amount
          when t.action = 'TRANSFER' and t.from_account_id = a_1.id then -t.amount
          else 0::numeric
        end), 0::numeric))::numeric(14,2) as balance
   from accounts a_1
   left join transactions t on a_1.id = t.account_id or a_1.id = t.from_account_id or a_1.id = t.to_account_id
   group by a_1.id
 )
 select a.id,
   a.name,
   a.currency,
   a.is_monobank,
   (case
      when a.is_monobank and ms.balance_kop is not null
        then round((ms.balance_kop - ms.credit_limit_kop)::numeric / 100.0, 2)
      else c.balance
    end)::numeric(14,2) as balance,
   (a.is_monobank and ms.balance_kop is not null) as live,
   case when a.is_monobank then ms.updated_at else null::timestamptz end as live_at,
   case when a.is_monobank and ms.balance_kop is not null
        then round(ms.balance_kop::numeric / 100.0, 2) else null::numeric end as available,
   case when a.is_monobank and ms.balance_kop is not null
        then round(ms.credit_limit_kop::numeric / 100.0, 2) else null::numeric end as credit_limit
 from accounts a
 join calc c on c.id = a.id
 left join mono_state ms on ms.id = 1;

